-- Run this in Supabase Dashboard > SQL Editor > New query.
create table if not exists public.customer_claims (
  id bigint generated by default as identity primary key,
  customer_name text not null check (char_length(customer_name) between 2 and 100),
  mobile_number text not null,
  winning_prize text not null check (winning_prize in (
    'Flat 25% off on Making Charges',
    '₹1000 shopping voucher',
    'Free Silver Coin',
    'Flat 50% off on Making Charges',
    'Special Gift 🎁'
  )),
  redemption_code text not null unique,
  claimed_at timestamptz not null default now()
);

alter table public.customer_claims enable row level security;

-- Intentionally create no public SELECT/INSERT/UPDATE/DELETE policies.
-- The Vercel serverless function writes using the server-only secret key.
